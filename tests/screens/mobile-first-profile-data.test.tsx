it('clears fields and errors when authorization changes to OTP verification', () => {
  const callbacks = { onBack: vi.fn(), onClose: vi.fn(), onConfirm: vi.fn() }
  const view = render(<DataAuthorize {...callbacks} />)
  enter('Mobile Code', '123456')
  view.rerender(<DataAuthorize otp {...callbacks} />)
  expect(screen.getByLabelText('Codice di verifica')).toHaveValue('')
  expect(screen.getByRole('button', { name: 'Conferma' })).toBeDisabled()
})
it('requires an independently entered OTP after authorizing a phone change with a current six-digit Mobile Code', () => {
  expect(changeCredential('mobile', '12345678', '583927', '583927')).toBeNull()
  show()
  click('Modifica Numero di cellulare')
  enter('Numero di cellulare', '3451280954')
  enter('Operatore telefonico', 'Vodafone Italia')
  fireEvent.click(screen.getByRole('checkbox'))
  click('Conferma')
  enter('Mobile Code', '583927')
  click('Conferma')
  expect(screen.getByLabelText('Codice di verifica')).toHaveValue('')
  expect(screen.getByRole('button', { name: 'Conferma' })).toBeDisabled()
  expect(getProfileDataSnapshot().phone).toBe('3351267799')
  enter('Codice di verifica', '000000')
  click('Conferma')
  expect(screen.getByRole('alert')).toBeInTheDocument()
  click('Indietro')
  enter('Mobile Code', '583927')
  click('Conferma')
  expect(screen.getByLabelText('Codice di verifica')).toHaveValue('')
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  enter('Codice di verifica', '123456')
  click('Conferma')
  expect(getProfileDataSnapshot().phone).toBe('3451280954')
})
it('discards the old merge draft when choosing a different pair', () => {
  show('contacts')
  click('Unisci contatti')
  fireEvent.click(screen.getByLabelText('Antonio Fumagalli'))
  fireEvent.click(screen.getByLabelText('Alessia Colombo'))
  click('Continua')
  click('Modifica')
  enter('Nominativo', 'Old merged draft')
  click('Indietro')
  click('Indietro')
  fireEvent.click(screen.getByLabelText('Andrea Moretti'))
  fireEvent.click(screen.getByLabelText('Alberto Moretti'))
  click('Continua')
  expect(screen.queryByText('Old merged draft')).not.toBeInTheDocument()
  click('Conferma')
  enter('Mobile Code', '12345678')
  click('Conferma')
  const result = getContactsSnapshot()
  expect(result.find((c) => c.id === 'contact-2')?.name).toBe('Andrea Moretti')
  expect(result.find((c) => c.id === 'contact-2')?.relationships).toHaveLength(2)
  expect(result.some((c) => c.id === 'contact-3')).toBe(false)
  expect(result.some((c) => c.id === 'contact-0')).toBe(true)
  expect(result.some((c) => c.id === 'contact-1')).toBe(true)
})
it('restores a canceled contact draft in detail and the next edit', () => {
  show('contacts')
  click('AC Alessia Colombo')
  click('Modifica contatto')
  enter('Nominativo', 'Unsaved name')
  enter('Alias', 'Unsaved alias')
  click('Indietro')
  expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent('Alessia Colombo')
  expect(screen.queryByText('Unsaved alias')).not.toBeInTheDocument()
  click('Modifica contatto')
  expect(screen.getByLabelText('Nominativo')).toHaveValue('Alessia Colombo')
  expect(screen.getByLabelText('Alias')).toHaveValue('Alessia.Colombo')
  click('Salva')
  enter('Mobile Code', '12345678')
  click('Conferma')
  expect(getContactsSnapshot().find((c) => c.id === 'contact-1')?.name).toBe('Alessia Colombo')
})
it('selects a value in the source bottom sheet only on confirmation and cancels safely', () => {
  const onChange = vi.fn()
  render(<DataSelect label="Rapporto" value="" options={['Conto', 'Cellulare']} onChange={onChange} />)
  fireEvent.mouseDown(screen.getByLabelText('Rapporto'))
  fireEvent.click(within(screen.getByRole('dialog')).getByLabelText('Cellulare'))
  fireEvent.click(screen.getByRole('button', { name: 'Chiudi selezione' }))
  expect(onChange).not.toHaveBeenCalled()
  fireEvent.mouseDown(screen.getByLabelText('Rapporto'))
  fireEvent.click(within(screen.getByRole('dialog')).getByLabelText('Cellulare'))
  fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
  expect(onChange).toHaveBeenCalledWith('Cellulare')
})
