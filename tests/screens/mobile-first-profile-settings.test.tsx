// @vitest-environment jsdom
import { beforeEach, afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { profileSettingsStore } from '@/features/profile/mobileFirstProfileSettings'
import MobileFirstProfileSettings from '@/experiences/pi/it/mobile-first/MobileFirstProfileSettings'
beforeEach(() => profileSettingsStore.reset())
afterEach(cleanup)
const start = () => render(<MobileFirstProfileSettings onBack={vi.fn()} onClose={vi.fn()} />)
describe('Italy profile settings journeys', () => {
  it('saves language and preserves it when returning to settings', () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: /Generali/ }))
    fireEvent.click(screen.getByRole('button', { name: /Lingua/ }))
    fireEvent.click(screen.getByRole('radio', { name: 'English' }))
    fireEvent.click(screen.getByRole('button', { name: 'Salva modifiche' }))
    expect(profileSettingsStore.getSnapshot().language).toBe('English')
  })
  it('keeps screenshot edits pending until save and describes background privacy tradeoff', () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: /^Sicurezza/ }))
    fireEvent.click(screen.getByRole('button', { name: /Screenshot/ }))
    expect(screen.getByText(/non sarà possibile oscurare/)).toBeTruthy()
    fireEvent.click(screen.getByRole('switch', { name: 'Abilita screenshot' }))
    expect(profileSettingsStore.getSnapshot().screenshots).toBe(false)
    fireEvent.click(screen.getByRole('button', { name: 'Salva le modifiche' }))
    expect(profileSettingsStore.getSnapshot().screenshots).toBe(true)
  })
  it('does not modify PIN when confirmation is mismatched', () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: /^Sicurezza/ }))
    fireEvent.click(screen.getByRole('button', { name: /^PIN/ }))
    fireEvent.change(screen.getByLabelText('Inserisci PIN attuale'), { target: { value: '87263915' } })
    fireEvent.change(screen.getByLabelText('Inserisci nuovo PIN'), { target: { value: '59382746' } })
    fireEvent.change(screen.getByLabelText('Conferma il nuovo PIN'), { target: { value: '59382745' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salva le modifiche' }))
    expect(screen.getByRole('alert').textContent).toContain('corrispondono')
  })
  it('requires document acknowledgement before instant-limit authorization and persists only after confirmation', async () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: /Limiti e operatività/ }))
    fireEvent.click(screen.getByRole('button', { name: /^Limiti/ }))
    fireEvent.click(screen.getByRole('radio', { name: /Filippo/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Prosegui' }))
    fireEvent.change(screen.getByLabelText('Importo limite'), { target: { value: '20000' } })
    fireEvent.click(screen.getByRole('button', { name: 'Prosegui' }))
    expect(profileSettingsStore.getSnapshot().instantLimits.filippo?.amount).toBe(15000)
    fireEvent.click(screen.getByRole('button', { name: 'Continua' }))
    expect((screen.getByRole('button', { name: 'Accetta e prosegui' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Visualizza il documento PDF' }))
    fireEvent.click(screen.getByRole('switch', { name: 'Confermo di aver preso visione' }))
    fireEvent.click(screen.getByRole('button', { name: 'Accetta e prosegui' }))
    fireEvent.change(screen.getByLabelText('Mobile Code'), { target: { value: '12345678' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    await waitFor(() => expect(profileSettingsStore.getSnapshot().instantLimits.filippo?.amount).toBe(20000))
  })
  it('requires explicit confirmation to remove a category notification', () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: /^Notifiche/ }))
    fireEvent.click(screen.getByRole('button', { name: /Bilancio familiare e budget/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Gestisci categorie' }))
    fireEvent.click(screen.getByRole('button', { name: 'Elimina Trasporti - Bus e Metro' }))
    expect(profileSettingsStore.getSnapshot().categoryNotifications).toContain('Trasporti - Bus e Metro')
    fireEvent.click(screen.getByRole('button', { name: 'Conferma eliminazione' }))
    expect(profileSettingsStore.getSnapshot().categoryNotifications).not.toContain('Trasporti - Bus e Metro')
  })
  it('opens security levels and missions without executing OS actions', () => {
    render(<MobileFirstProfileSettings entry="security" onBack={vi.fn()} onClose={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Scopri i livelli' }))
    expect(screen.getByText('Livello alto')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Indietro' }))
    fireEvent.click(screen.getByRole('button', { name: 'Scopri tutte le missioni' }))
    fireEvent.click(screen.getByRole('button', { name: /Ripristina il dispositivo/ }))
    expect(screen.getByText(/Riporta il device alle impostazioni di fabbrica/)).toBeTruthy()
  })
  it('checks recapito validation and confirmation before completing a security mission', () => {
    render(<MobileFirstProfileSettings entry="security" onBack={vi.fn()} onClose={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Scopri tutte le missioni' }))
    fireEvent.click(screen.getByRole('button', { name: /Verifica la tua email/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Verifica recapito' }))
    fireEvent.change(screen.getByLabelText('Email'), { target: { value: 'user@example.it' } })
    fireEvent.click(screen.getByRole('button', { name: 'Invia codice di verifica' }))
    fireEvent.change(screen.getByLabelText('Codice di verifica'), { target: { value: '000000' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    expect(profileSettingsStore.getSnapshot().missions).not.toContain('email')
    fireEvent.change(screen.getByLabelText('Codice di verifica'), { target: { value: '123456' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    expect(profileSettingsStore.getSnapshot().missions).toContain('email')
  })
  it('cannot enable quick operations before selecting an account and accepting costs', async () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: /^Operazioni veloci/ }))
    fireEvent.click(screen.getByRole('button', { name: /^Operazioni veloci/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Attiva' }))
    fireEvent.click(screen.getByRole('button', { name: 'Continua' }))
    expect((screen.getByRole('button', { name: 'Continua' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('switch', { name: /Andrea Rossini/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Continua' }))
    fireEvent.click(screen.getByRole('button', { name: 'Continua' }))
    expect(screen.getByRole('alert').textContent).toContain('costi')
    fireEvent.click(screen.getByRole('switch', { name: 'Ho preso visione dei costi' }))
    fireEvent.click(screen.getByRole('button', { name: 'Continua' }))
    expect(profileSettingsStore.getSnapshot().quickEnabled).toBe(false)
    fireEvent.change(screen.getByLabelText('Mobile Code'), { target: { value: '12345678' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    await waitFor(() => expect(profileSettingsStore.getSnapshot().quickEnabled).toBe(true))
    expect(profileSettingsStore.getSnapshot().quickDefault).toBe('andrea')
  })
  it('displays third-party invalid-code errors and confirms selected data sharing only after authorization', async () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: 'Terze parti' }))
    fireEvent.click(screen.getByRole('button', { name: 'Utilizza codice fornito dalla terza parte' }))
    fireEvent.change(screen.getByLabelText('Codice univoco fornito dalla terza parte'), { target: { value: 'WRONG' } })
    fireEvent.click(screen.getByRole('button', { name: 'Prosegui' }))
    expect(screen.getByRole('alert').textContent).toContain('non è corretto')
    fireEvent.change(screen.getByLabelText('Codice univoco fornito dalla terza parte'), { target: { value: 'YADITY' } })
    fireEvent.click(screen.getByRole('button', { name: 'Prosegui' }))
    fireEvent.click(screen.getByRole('switch', { name: 'Condividi transazioni' }))
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    fireEvent.change(screen.getByLabelText('Mobile Code'), { target: { value: '12345678' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    await waitFor(() => expect(profileSettingsStore.getSnapshot().consents.length).toBe(7))
    expect(profileSettingsStore.getSnapshot().consents.at(-1)).toMatchObject({
      balance: true,
      transactions: false,
      status: 'Attivo',
    })
  })
  it('shows a clear warning before replacing the existing instant-limit type', () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: /Limiti e operatività/ }))
    fireEvent.click(screen.getByRole('button', { name: /^Limiti/ }))
    fireEvent.click(screen.getByRole('radio', { name: /Filippo/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Prosegui' }))
    fireEvent.click(screen.getByRole('radio', { name: 'Limite giornaliero' }))
    fireEvent.click(screen.getByRole('button', { name: 'Prosegui' }))
    expect(screen.getByText(/Stai disattivando il limite/)).toBeTruthy()
    expect(profileSettingsStore.getSnapshot().instantLimits.filippo?.kind).toBe('operation')
  })
  it('keeps privacy choices pending through document signing and completes them after authorization', async () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: 'Consensi e Privacy' }))
    fireEvent.click(screen.getByRole('button', { name: 'Modifica privacy' }))
    fireEvent.click(screen.getAllByRole('radio', { name: 'Non acconsento' })[0]!)
    fireEvent.click(screen.getByRole('button', { name: 'Prosegui' }))
    fireEvent.click(screen.getByRole('button', { name: 'Avanti' }))
    expect(screen.getByAltText('Facsimile documento consensi privacy')).toBeTruthy()
    expect(profileSettingsStore.getSnapshot().privacy[0]).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Visualizza il documento PDF' }))
    fireEvent.click(screen.getByRole('button', { name: 'Accetta e prosegui' }))
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    fireEvent.change(screen.getByLabelText('Mobile Code'), { target: { value: '12345678' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    await waitFor(() => expect(profileSettingsStore.getSnapshot().privacy[0]).toBe(false))
    expect(screen.getByRole('heading', { name: 'La sottoscrizione si è conclusa correttamente!' })).toBeTruthy()
  })
  it('returns to security controls after checking protection and consumes the recovery entry once', () => {
    render(<MobileFirstProfileSettings initialFlow="forgot-mobile-code" onBack={vi.fn()} onClose={vi.fn()} />)
    expect(screen.getByRole('heading', { name: 'Creazione di un nuovo Mobile Code' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Indietro' }))
    expect(screen.getByRole('button', { name: /^PIN/ })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Indietro' }))
    fireEvent.click(screen.getByRole('button', { name: 'Sicurezza' }))
    expect(screen.getByRole('button', { name: /^PIN/ })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: /Check up sicurezza/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Indietro' }))
    expect(screen.getByRole('button', { name: /^PIN/ })).toBeTruthy()
  })
  it('discards access-history filter edits on Back without changing applied results', () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: 'Sicurezza' }))
    fireEvent.click(screen.getByRole('button', { name: /Storico accessi/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Filtra accessi' }))
    fireEvent.change(screen.getByLabelText('Dal'), { target: { value: '2025-01-20' } })
    fireEvent.change(screen.getByLabelText('Al'), { target: { value: '2025-01-20' } })
    fireEvent.click(screen.getByRole('radio', { name: 'App' }))
    fireEvent.click(screen.getByRole('button', { name: 'Applica filtri' }))
    expect(screen.getAllByText('App')).toHaveLength(4)
    fireEvent.click(screen.getByRole('button', { name: 'Filtra accessi' }))
    fireEvent.change(screen.getByLabelText('Dal'), { target: { value: '2025-01-21' } })
    fireEvent.click(screen.getByRole('radio', { name: 'Web' }))
    fireEvent.click(screen.getByRole('button', { name: 'Indietro' }))
    expect(screen.getAllByText('App')).toHaveLength(4)
    expect(screen.queryByText('Nessun accesso nel periodo selezionato.')).toBeNull()
  })
  it('saves a group notification preference without disabling the master switch or other groups', () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: 'Notifiche' }))
    fireEvent.click(screen.getByRole('button', { name: /Conti correnti/ }))
    fireEvent.click(screen.getByRole('switch', { name: 'Abilita le notifiche' }))
    fireEvent.click(screen.getByRole('button', { name: 'Salva modifiche' }))
    expect(profileSettingsStore.getSnapshot().notificationsEnabled).toBe(true)
    expect(profileSettingsStore.getSnapshot().notificationGroupEnabled['Conti correnti']).toBe(false)
    fireEvent.click(screen.getByText('Chiudi', { exact: true }))
    fireEvent.click(screen.getByRole('button', { name: /^Carte/ }))
    expect((screen.getByRole('switch', { name: 'Abilita le notifiche' }) as HTMLInputElement).checked).toBe(true)
  })
  it('requires a freshly entered verification code for every newsletter email change', () => {
    start()
    fireEvent.click(screen.getByRole('button', { name: 'Newsletter' }))
    fireEvent.click(screen.getByRole('button', { name: /^Email/ }))
    fireEvent.change(screen.getByLabelText('Email'), { target: { value: 'first@example.it' } })
    fireEvent.click(screen.getByRole('button', { name: 'Invia codice di verifica' }))
    fireEvent.change(screen.getByLabelText('Codice di verifica'), { target: { value: '123456' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    expect(profileSettingsStore.getSnapshot().email).toBe('first@example.it')
    fireEvent.click(screen.getByRole('button', { name: /^Email/ }))
    fireEvent.change(screen.getByLabelText('Email'), { target: { value: 'second@example.it' } })
    fireEvent.click(screen.getByRole('button', { name: 'Invia codice di verifica' }))
    expect((screen.getByLabelText('Codice di verifica') as HTMLInputElement).value).toBe('')
    fireEvent.click(screen.getByRole('button', { name: 'Conferma' }))
    expect(profileSettingsStore.getSnapshot().email).toBe('first@example.it')
    expect(screen.getByRole('alert')).toBeTruthy()
  })
  it('opens the full security pill collection and the chosen educational topic', () => {
    render(<MobileFirstProfileSettings entry="security" onBack={vi.fn()} onClose={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Scopri tutte le pillole di sicurezza' }))
    expect(screen.getByRole('heading', { name: 'Pillole di sicurezza' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Tutelati dalle truffe al telefono' }))
    expect(screen.getByRole('heading', { name: 'Tutelati dalle truffe al telefono' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Scopri di più' }))
    expect(screen.getByRole('heading', { name: 'Pillole di sicurezza' })).toBeTruthy()
  })
  it('sends the applied access-history report to the verified email in local prototype state', () => {
    profileSettingsStore.update({ email: 'andrearossini@email.it', emailVerified: true })
    start()
    fireEvent.click(screen.getByRole('button', { name: 'Sicurezza' }))
    fireEvent.click(screen.getByRole('button', { name: /Storico accessi/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Invia storico' }))
    expect(screen.getByRole('heading', { name: 'Invia storico via email' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Invia storico' }))
    expect(profileSettingsStore.getSnapshot().lastAccessHistoryDelivery).toMatchObject({
      recipient: 'andrearossini@email.it',
      count: 14,
      status: 'sent',
    })
    expect(screen.getByRole('heading', { name: 'Storico accessi inviato con successo!' })).toBeTruthy()
  })
  it('opens the digital-signature flow directly from a service prerequisite', () => {
    profileSettingsStore.update({ signature: 'Non attiva' })
    render(<MobileFirstProfileSettings initialFlow="digital-signature" onBack={vi.fn()} onClose={vi.fn()} />)
    expect(screen.getByRole('heading', { name: 'Firma digitale' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Attiva' }))
    expect(screen.getByRole('heading', { name: 'Richiesta di certificato per la firma digitale' })).toBeTruthy()
  })
})
