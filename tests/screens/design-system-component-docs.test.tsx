// @vitest-environment jsdom
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { afterEach, expect, it, vi } from 'vitest'
import '@testing-library/jest-dom/vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { DemoProvider } from '@/app/state/demoStore'
import { LanguageProvider } from '@/app/contexts/LanguageContext'
import { COMPONENT_REGISTRY } from '@/app/registry/componentRegistry'
import { getComponentImplementationPackage } from '@/app/registry/componentImplementationPackages'
import type { ComponentId } from '@/app/state/demoTypes'
import { getNativeDesignSystemPreview } from '@/features/demo-native/designSystemPreview'
import FigmaLibraryFamilyView from '@/app/screens/design-system/FigmaLibraryFamily'
import { resolveFigmaStates } from '@/app/screens/design-system/FigmaStateGallery'
import { FIGMA_IMPLEMENTATION_GROUPS, FIGMA_LIBRARY_PAGES } from '@/app/screens/design-system/figmaLibraryCatalog'

vi.mock('@/app/components/demo/NativeScreenPreview', () => ({
  NativeScreenPreview: ({ snapshot }: { snapshot: { componentPreview?: { componentId: string } } }) => (
    <div data-testid="native-component" data-implementation={snapshot.componentPreview?.componentId} />
  ),
}))

afterEach(cleanup)

const GENERIC_SUMMARY = /^Shared executable component aligned with the canonical Figma source|^Portable reference/

function renderFamily(
  page: (typeof FIGMA_LIBRARY_PAGES)[number],
  family: (typeof FIGMA_LIBRARY_PAGES)[number]['families'][number],
) {
  return render(
    <DemoProvider initialState={{ country: 'RO' }}>
      <LanguageProvider initialLanguage="en">
        <FigmaLibraryFamilyView page={page} family={family} />
      </LanguageProvider>
    </DemoProvider>,
  )
}

it('documents every Figma family, live or not, with the same header and tabs', () => {
  const families = FIGMA_LIBRARY_PAGES.flatMap((page) => page.families.map((family) => ({ page, family })))
  expect(families.length).toBeGreaterThan(100)
  for (const { page, family } of families) {
    renderFamily(page, family)
    const tabs = within(screen.getByRole('tablist')).getAllByRole('tab')
    expect(tabs[0]).toHaveTextContent('Overview')
    expect(screen.getByRole('heading', { level: 1 })).toBeInTheDocument()
    expect(screen.getByRole('navigation', { name: 'Breadcrumb' })).toHaveTextContent(page.name)
    for (const tab of tabs) {
      fireEvent.click(tab)
      expect(tab).toHaveAttribute('aria-selected', 'true')
      expect(screen.getByRole('tabpanel')).toBeInTheDocument()
    }
    cleanup()
  }
})

it('opens all 71 live components without template boilerplate', () => {
  expect(FIGMA_IMPLEMENTATION_GROUPS).toHaveLength(71)
  for (const group of FIGMA_IMPLEMENTATION_GROUPS) {
    const page = group.page
    renderFamily(page, group.family)
    const article = document.querySelector('[data-component-overview-sections]')!
    expect(article).toBeInTheDocument()
    expect(article.textContent).not.toMatch(/See the component source for contextual overrides/)
    expect(article.textContent).not.toMatch(/Policy ownership|Inspector OFF|Source only/)
    expect(within(screen.getByRole('tablist')).getByRole('tab', { name: 'Code' })).toBeInTheDocument()
    expect(getComponentImplementationPackage(group.id)?.summary).not.toMatch(GENERIC_SUMMARY)
    cleanup()
  }
})

it('reports the documentation still missing for each live component', () => {
  const rows = FIGMA_IMPLEMENTATION_GROUPS.map((group) => {
    const data = getComponentImplementationPackage(group.id)
    const native = getNativeDesignSystemPreview(group.id)
    const states = resolveFigmaStates(group.sources, group.id, native?.variants ?? [])
    const meta = COMPONENT_REGISTRY[group.id as ComponentId]
    const missing = [
      !data?.usage && 'usage guidance',
      !meta?.usedByScreens.length && 'screens using it',
      !data?.accessibilitySpecifications.length && 'accessibility',
      states.perState &&
        states.built < states.total &&
        `${states.total - states.built} Figma states without a live preview`,
      !states.perState && 'per-state previews',
    ].filter(Boolean) as string[]
    return { id: group.id, label: group.label, missing }
  })
  expect(rows).toHaveLength(71)
  if (process.env.npm_lifecycle_event === 'audit:component-docs') {
    const complete = rows.filter((row) => !row.missing.length).length
    const lines = [
      '# Component documentation completeness',
      '',
      `Generated by \`npm run audit:component-docs\`. ${complete} of ${rows.length} live components are complete.`,
      '',
      '| Component | Id | Missing |',
      '| --- | --- | --- |',
      ...rows.map((row) => `| ${row.label} | \`${row.id}\` | ${row.missing.join(', ') || '—'} |`),
      '',
    ]
    writeFileSync(resolve('docs/design-system/component-docs-completeness.md'), lines.join('\n'))
  }
})
