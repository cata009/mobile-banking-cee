export type PaymentImageVariant = keyof typeof PAYMENT_IMAGE_ARTWORK
export type CardArtVariant = keyof typeof CARD_ARTWORK_IMAGES
export type ResolvedImageArtwork = ImageArtworkSource & { width: number; height: number; scale: number }

function resolveSource(source: ImageArtworkSource, width: number): ResolvedImageArtwork {
  if (!Number.isFinite(width) || width <= 0) throw new RangeError('Artwork width must be finite and positive')
  const scale = width / source.intrinsicWidth
  return { ...source, width, height: source.intrinsicHeight * scale, scale }
}
export function resolvePaymentImage({
  variant = 'MakePayment',
  width = 137,
}: { variant?: PaymentImageVariant; width?: number } = {}) {
  return resolveSource(PAYMENT_IMAGE_ARTWORK[variant], width)
}
export function resolveCardArt({
  variant = 'Credit red arrow gold',
  width = 219,
}: { variant?: CardArtVariant; width?: number } = {}) {
  return resolveSource(CARD_ARTWORK_IMAGES[variant], width)
}
